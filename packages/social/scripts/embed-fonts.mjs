#!/usr/bin/env node
//
// THE CARDS' FONTS, EMBEDDED: fonts/*.ttf -> src/cards/font-data.ts (base64).
//
// Why embedded rather than read from disk: a card route that reads a font
// file at request time reads a path the bundler can't follow, so a deployed
// app draws every card in a fallback face unless somebody remembers to name
// the files for its file tracing (Almanac had to, in next.config.ts). Inside
// a package that is somebody else's node_modules, in a bundler we don't
// choose. As a string in a module the bytes go wherever the module goes:
// Next, Vite, a plain Node server, an edge runtime. About 320 KB, in the one
// route that draws cards (./fonts is its own entry, so nothing else loads it).
//
// Run after changing a file in fonts/:  pnpm --filter @adminigloo/social embed-fonts
// src/__tests__/fonts.test.ts fails when the two disagree.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = readdirSync(join(ROOT, "fonts"))
  .filter((name) => name.endsWith(".ttf"))
  .sort();

const lines = [
  "// GENERATED by scripts/embed-fonts.mjs from fonts/*.ttf. Do not edit: change a",
  "// font file and run `pnpm --filter @adminigloo/social embed-fonts`.",
  "// src/__tests__/fonts.test.ts holds the two together.",
  "",
  "/** Each bundled font file's bytes, base64, by file name. Read through `cardFonts()` (./fonts.ts). */",
  "export const CARD_FONT_DATA: Readonly<Record<string, string>> = {",
  ...files.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(ROOT, "fonts", name)).toString("base64"))},`),
  "};",
  "",
];
writeFileSync(join(ROOT, "src", "cards", "font-data.ts"), lines.join("\n"));
console.log(`embedded ${files.length} fonts into src/cards/font-data.ts`);
