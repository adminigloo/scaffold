import { storageNames, type DefineStorageTablesOptions } from "./names.js";

/**
 * The shipped SQL (D14, section 6.1), for a host that doesn't run
 * drizzle-kit: Ridgeline pastes `storageSql({ schema: "adminigloo" })` into a
 * Prisma migration of its own, so every environment gets it and its drift
 * check stays clean. `sql/storage-0.2.0.sql` is `storageSql()` (a test
 * asserts the file equals it) and `sql/upgrade-0.1-to-0.2.sql` is
 * `storageUpgradeSql()`.
 *
 * EACH OPENS WITH A GUARD (review G1). `create table if not exists` quietly
 * skips over a table that is already there, so a host with its OWN table
 * named `stored_files` would get "success", our indexes on its table, and a
 * package pointing every statement at the host's rows. The guard RAISES when
 * the target exists and isn't this package's 0.2 table (it has no
 * `purge_attempts`), naming the way out: a prefix or a schema, or (for
 * AdminIgloo's own 0.1 table) the upgrade.
 *
 * EACH FILE IS ONE STATEMENT (review FH-1). The guard and every CREATE (or
 * ALTER) after it are a single DO block, so the guard's RAISE stops ALL of
 * it, whatever runs the file. `psql -f` runs a file statement by statement,
 * with autocommit on and ON_ERROR_STOP off: with the guard as a block of its
 * own, psql printed the refusal and went on to put every index whose columns
 * happened to exist (a UNIQUE one on `pathname` included) on the host's own
 * table. A block can't be split, so there is nothing after the refusal to run.
 *
 * WHY pg_attribute AND NOT information_schema. `to_regclass('stored_files')`
 * resolves through the search path; information_schema needs the schema
 * spelled out, and `current_schema()` is not always where the search path
 * found the table. Asking pg_attribute about the very relation to_regclass
 * found can't disagree with it.
 */

function literal(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Indented once, for the body of the DO block. */
function indent(lines: readonly string[]): string[] {
  return lines.map((line) => (line === "" ? "" : `  ${line}`));
}

/** One DO block around `body`: one statement, so no runner can run part of it. */
function oneBlock(body: readonly string[]): string[] {
  return ["do $$", "begin", ...indent(body), "end $$;"];
}

function guard(regclass: string, column: string, message: string): string[] {
  return [
    `if to_regclass(${literal(regclass)}) is not null and not exists (`,
    `  select 1 from pg_attribute where attrelid = to_regclass(${literal(regclass)}) and attname = ${literal(column)} and not attisdropped`,
    ") then",
    `  raise exception ${literal(message)};`,
    "end if;",
  ];
}

/** How to run a shipped file by hand, in its header. */
const HOW_TO_RUN =
  "-- One statement (a DO block): the guard's refusal stops all of it, however it is run. By hand: psql -1 -v ON_ERROR_STOP=1 -f <this file>.";

/** The DDL for the storage table under `options`: guard, schema, table and indexes, every statement "if not exists". */
export function storageSql(options: DefineStorageTablesOptions = {}): string {
  const n = storageNames(options);
  const q = n.qualified;
  const header: string[] = [
    `-- @adminigloo/storage 0.2.0: the stored files table (${n.display}).`,
    `-- Generated by storageSql(${n.schema || n.prefix ? JSON.stringify({ ...(n.prefix ? { prefix: n.prefix } : {}), ...(n.schema ? { schema: n.schema } : {}) }) : ""}).`,
    "-- Safe to run twice. The guard refuses to run over a table of the same name that isn't this package's.",
    HOW_TO_RUN,
  ];
  if (n.prefix && !n.schema) {
    // Review FH-2: a prefixed table lives in `public`, which `prisma migrate
    // dev` compares with schema.prisma; with no model for it, the next
    // migration Prisma writes drops it. A schema of its own is invisible to it.
    header.push(
      '-- With Prisma, give it a schema of its own (storageSql({ schema: "adminigloo" })), not only a prefix: a prefixed table sits in public, and the next `prisma migrate dev` writes a migration that drops it.',
    );
  }
  const body: string[] = [
    ...guard(
      q,
      "purge_attempts",
      `A table named ${n.display} already exists and isn't AdminIgloo's. Pass a prefix or a schema. (If it is AdminIgloo's storage 0.1 table, run sql/upgrade-0.1-to-0.2.sql instead.)`,
    ),
    "",
  ];
  if (n.schema) body.push(`create schema if not exists "${n.schema}";`, "");
  body.push(
    `create table if not exists ${q} (`,
    `  "id" text primary key,`,
    `  "tenant_id" text not null,`,
    `  "owner_id" text,`,
    `  "kind" text not null,`,
    `  "filename" text not null,`,
    `  "content_type" text not null,`,
    `  "size_bytes" integer not null,`,
    `  "pathname" text not null,`,
    `  "url" text,`,
    `  "access" text not null default 'public',`,
    `  "record_type" text,`,
    `  "record_id" text,`,
    `  "width" integer,`,
    `  "height" integer,`,
    `  "sha256" text,`,
    `  "deleted_at" timestamp with time zone,`,
    `  "purge_attempts" integer not null default 0,`,
    `  "created_at" timestamp with time zone not null default now()`,
    `);`,
    "",
    ...indexStatements(n),
  );
  return `${[...header, "", ...oneBlock(body)].join("\n")}\n`;
}

function indexStatements(n: ReturnType<typeof storageNames>): string[] {
  const q = n.qualified;
  return [
    `create index if not exists "${n.indexes.tenantCreated}" on ${q} ("tenant_id", "created_at");`,
    `create index if not exists "${n.indexes.tenantKind}" on ${q} ("tenant_id", "kind");`,
    `create unique index if not exists "${n.indexes.pathname}" on ${q} ("pathname");`,
    `create index if not exists "${n.indexes.record}" on ${q} ("tenant_id", "record_type", "record_id") where deleted_at is null;`,
    `create index if not exists "${n.indexes.live}" on ${q} ("tenant_id", "created_at", "id") where deleted_at is null;`,
    `create index if not exists "${n.indexes.purge}" on ${q} ("deleted_at") where deleted_at is not null;`,
  ];
}

const V01_COLUMNS = ["id", "tenant_id", "owner_id", "kind", "filename", "content_type", "size_bytes", "pathname", "url", "created_at"];
const V02_COLUMNS = [
  ...V01_COLUMNS,
  "access",
  "record_type",
  "record_id",
  "width",
  "height",
  "sha256",
  "deleted_at",
  "purge_attempts",
];

function textArray(items: readonly string[]): string {
  return `array[${items.map(literal).join(", ")}]::text[]`;
}

/**
 * 0.1 → 0.2 for the default names (0.1 had no other). Its guard (review G1):
 * the table must have EXACTLY 0.1's columns and 0.1's index
 * `stored_files_tenant_created_idx`, else it raises and nothing is altered,
 * so the upgrade never ALTERs a host's own `stored_files`. The guard and the
 * ALTER are one DO block (review FH-1), so `psql -f` can't run the ALTER
 * after the refusal either.
 *
 * // CONTRACT: 6.1 says the upgrade raises unless the table is exactly 0.1's.
 * It also passes, as a no-op, over a table that is already exactly this
 * package's 0.2 table (every ALTER below is "if not exists"), so running it
 * twice by mistake is harmless instead of an alarming error. A host's table
 * is neither, and still raises.
 */
export function storageUpgradeSql(): string {
  const n = storageNames();
  const cols = `array(select attname::text from pg_attribute where attrelid = to_regclass('"stored_files"') and attnum > 0 and not attisdropped)`;
  const exactly = (expected: readonly string[]) =>
    `(${cols} @> ${textArray(expected)} and ${cols} <@ ${textArray(expected)})`;
  const body = [
    `if to_regclass('"stored_files"') is null then`,
    `  raise exception ${literal("There's no table named stored_files to upgrade. Run sql/storage-0.2.0.sql to create it.")};`,
    "end if;",
    `if not (`,
    `  (${exactly(V01_COLUMNS)} and exists (`,
    `    select 1 from pg_index i join pg_class c on c.oid = i.indexrelid`,
    `     where i.indrelid = to_regclass('"stored_files"') and c.relname = 'stored_files_tenant_created_idx'`,
    `  ))`,
    `  or ${exactly(V02_COLUMNS)}`,
    `) then`,
    `  raise exception ${literal("The table named stored_files isn't AdminIgloo's storage 0.1 table. Pass a prefix or a schema and run storageSql() instead.")};`,
    "end if;",
    "",
    'alter table "stored_files"',
    "  alter column owner_id drop not null,",
    "  alter column url drop not null,",
    "  add column if not exists access text not null default 'public',",
    "  add column if not exists record_type text,",
    "  add column if not exists record_id text,",
    "  add column if not exists width integer,",
    "  add column if not exists height integer,",
    "  add column if not exists sha256 text,",
    "  add column if not exists deleted_at timestamptz,",
    "  add column if not exists purge_attempts integer not null default 0;",
    "",
    ...indexStatements(n),
  ];
  return [
    "-- @adminigloo/storage: upgrade AdminIgloo's storage 0.1 table to 0.2 (the default name, stored_files).",
    "-- Every 0.1 row (and every 2a estimator photo) becomes a PUBLIC file of the company it was stored for",
    "-- (tenant '*': 0.1's firm-wide library, which no company's Files screen lists until it is given to one)",
    "-- and stays at its old public address until storage.moveToPrivate({ purpose }) moves it into the private store.",
    "-- The guard refuses to alter a table that isn't AdminIgloo's 0.1 (or 0.2) table.",
    HOW_TO_RUN,
    "",
    ...oneBlock(body),
    "",
  ].join("\n");
}
